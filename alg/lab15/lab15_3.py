def move_first_to_end(L):
    """
    Переносит первый элемент списка L в его конец.

    Параметры:
    L (list): Непустой список.

    Возвращает:
    list: Новый список с первым элементом в конце.
    """
    if not L:
        raise ValueError("Список должен быть непустым.")
    return L[1:] + [L[0]]

